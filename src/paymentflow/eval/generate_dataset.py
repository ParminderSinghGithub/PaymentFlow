def generate_dataset() -> list[dict]:
    """Build the dataset dictionary list."""
    dataset = []
    for c in CASES_DEF:
        case_id = c["id"]
        created_at_iso = BASE_TS.isoformat()

        # Build decision context
        decision_context = {
            "case_id": case_id,
            "failed_payment_id": f"pay_{case_id}_orig",
            "order_id": f"order_{case_id}",
            "customer_id": f"cust_{case_id}",
            "amount": c["amount"],
            "currency": c["currency"],
            "payment_method": c["method"],
            "failure_code": c["code"],
            "failure_description": c["desc"],
            "failure_source": c["src"],
            "failure_step": c["step"],
            "failure_reason": c["reason"],
            "failure_category": c["category"].value,
            "customer_tenure_months": c["tenure"],
            "prior_failed_count_24h": c["prior_f"],
            "prior_recovered_count_24h": c["prior_r"],
            "created_at": created_at_iso,
            "last_attempt_at": (
                "2026-08-30T09:55:00+00:00" if c.get("cooldown_active") else None
            ),
        }

        # Build ground truth
        ground_truth = {
            "customer_intent_score": c["intent"],
            "p_recovery_no_action": c["p_none"],
            "p_recovery_immediate_link": c["p_imm"],
            "p_recovery_delayed_link": c["p_del"],
            "p_recovery_escalate": c["p_esc"],
            "notes": c["notes"],
        }

        dataset.append({
            "decision_context": decision_context,
            "ground_truth": ground_truth,
        })
    return dataset


